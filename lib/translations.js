// Traduit une valeur à vocabulaire fixe (type ou couleur) vers la
// langue demandée ; si la valeur n'est pas dans le dictionnaire
// (ex. ancienne donnée), on retombe sur la valeur telle quelle.
export function translateFixedField(dictionary, value, locale) {
  return dictionary[value]?.[locale] ?? value;
}

// Renvoie le nom ou la description d'un produit dans la langue
// active, avec repli automatique sur le français si la traduction
// n'a pas été renseignée par le directeur.
export function localizeProductField(produit, field, locale) {
  if (locale === "fr") return produit[field] ?? "";
  return produit[`${field}_${locale}`] || produit[field] || "";
}

